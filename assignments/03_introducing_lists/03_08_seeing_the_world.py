# This program will print a list of places and print the list in different orders.

places = ["NYC", "London", "Sydney", "Seattle", "Philly"]

print(places)

print(sorted(places))

print(places)

print(sorted(places, reverse=True))

print(places)

places.reverse()
print(places)

places.reverse()
print(places)

places.reverse()
print(places)

places.sort(reverse=True)
print(places)